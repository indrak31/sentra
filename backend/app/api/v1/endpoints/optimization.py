"""OR-Tools emergency resource optimization endpoints."""

from math import ceil
from typing import Annotated, List, Optional
from fastapi import APIRouter, Depends, Query, status
from sqlalchemy.orm import Session
from app.api.deps import (
    get_db,
    require_permission,
    verify_user_geographic_scope,
)
from app.core.permissions import Permission
from app.models.allocation import Allocation
from app.models.user import User
from app.schemas.common import PaginatedResponse
from app.schemas.optimization import (
    AllocationRead,
    OptimizationRequest,
    OptimizationResponse,
)
from app.services.optimization_service import optimization_service
from app.services.resource_service import resource_service

router = APIRouter(prefix="/optimization", tags=["Resource Optimization"])


@router.post("/run", response_model=OptimizationResponse, status_code=status.HTTP_200_OK)
def trigger_optimization(
    req: OptimizationRequest,
    current_user: Annotated[User, Depends(require_permission(Permission.RUN_OPTIMIZATION))],
    db: Annotated[Session, Depends(get_db)],
) -> OptimizationResponse:
    """Execute mathematical emergency resource allocation using Google OR-Tools.

    Generates proposed allocation plans without automatically mutating live inventory.
    """
    if req.district_id:
        verify_user_geographic_scope(current_user, target_district_id=req.district_id)
    return optimization_service.run_optimization(db, req)


@router.get("/runs", response_model=PaginatedResponse[OptimizationResponse])
def list_optimization_runs(
    current_user: Annotated[User, Depends(require_permission(Permission.READ_OPTIMIZATION))],
    db: Annotated[Session, Depends(get_db)],
    district_id: Optional[str] = Query(None),
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
) -> PaginatedResponse[OptimizationResponse]:
    """List historical optimization executions and results."""
    if district_id:
        verify_user_geographic_scope(current_user, target_district_id=district_id)

    items, total = optimization_service.list_runs(
        db, district_id=district_id, page=page, page_size=page_size
    )
    # Map DB models to response schema
    mapped_items = [
        OptimizationResponse(
            run_id=r.id,
            status=r.status,
            solver_status=r.solver_status,
            objective_value=r.objective_value,
            allocations=[],
            unmet_demand=r.unmet_demand,
            unused_capacity=r.unused_capacity,
            result_summary=r.result_summary,
            completed_at=r.completed_at,
        )
        for r in items
    ]
    return PaginatedResponse(
        items=mapped_items,
        total=total,
        page=page,
        page_size=page_size,
        pages=ceil(total / page_size) if total > 0 else 1,
    )


@router.get("/runs/{run_id}", response_model=OptimizationResponse)
def get_optimization_run(
    run_id: str,
    current_user: Annotated[User, Depends(require_permission(Permission.READ_OPTIMIZATION))],
    db: Annotated[Session, Depends(get_db)],
) -> OptimizationResponse:
    """Retrieve full details of an optimization execution."""
    run = optimization_service.get_run(db, run_id)
    if run.district_id:
        verify_user_geographic_scope(current_user, target_district_id=run.district_id)

    return OptimizationResponse(
        run_id=run.id,
        status=run.status,
        solver_status=run.solver_status,
        objective_value=run.objective_value,
        allocations=[],
        unmet_demand=run.unmet_demand,
        unused_capacity=run.unused_capacity,
        result_summary=run.result_summary,
        completed_at=run.completed_at,
    )


@router.get("/runs/{run_id}/allocations", response_model=List[AllocationRead])
def get_run_allocations(
    run_id: str,
    current_user: Annotated[User, Depends(require_permission(Permission.READ_OPTIMIZATION))],
    db: Annotated[Session, Depends(get_db)],
) -> List[Allocation]:
    """Retrieve all specific resource allocation decisions generated by an optimization run."""
    run = optimization_service.get_run(db, run_id)
    if run.district_id:
        verify_user_geographic_scope(current_user, target_district_id=run.district_id)
    return optimization_service.list_allocations(db, run_id)


@router.post("/allocations/{allocation_id}/confirm", response_model=AllocationRead)
def confirm_allocation(
    allocation_id: str,
    current_user: Annotated[User, Depends(require_permission(Permission.CONFIRM_ALLOCATION))],
    db: Annotated[Session, Depends(get_db)],
) -> Allocation:
    """Confirm a proposed allocation and deduct from live inventory safely."""
    return resource_service.confirm_allocation(db, allocation_id)
